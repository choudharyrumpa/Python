# Program to check if a substring exists in a string

# Main string
main_string = "Python programming is fun"

# Substring to search
sub_string = "programming"

# 'in' keyword checks if the substring is present in the main string
if sub_string in main_string:
    print(f"Yes, '{sub_string}' is found in the main string.")
else:
    print(f"No, '{sub_string}' is NOT found in the main string.")
